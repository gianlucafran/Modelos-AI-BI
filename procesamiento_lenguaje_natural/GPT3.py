import os
from openai import OpenAI

def generar_respuesta(api_key, prompt):
    try:
        # Inicializa el cliente utilizando la API key ingresada por el usuario
        client = OpenAI(api_key=api_key)

        response = client.chat.completions.create(
            model="gpt-3.5-turbo",
            messages=[
                {"role": "system", "content": "Eres un asistente útil y conciso."},
                {"role": "user", "content": prompt}
            ],
            max_tokens=150,
            temperature=0.7
        )
        return response.choices[0].message.content

    except Exception as e:
        return f"Ocurrió un error: {e}"

if __name__ == "__main__":
    # Solicitamos la API key y la pregunta de forma interactiva
    api_key_usuario = input("Ingresa tu API Key de OpenAI: ").strip()
    pregunta = input("Escribe tu pregunta para el modelo: ")
    print(f"\nProcesando...\n")

    respuesta = generar_respuesta(api_key_usuario, pregunta)
    print(f"Respuesta:\n{respuesta}")