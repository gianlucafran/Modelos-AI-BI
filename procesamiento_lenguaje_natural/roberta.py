from transformers import AutoTokenizer, AutoModelForSequenceClassification, pipeline

def ejecutar_roberta_local():
    print("Cargando el tokenizador y el modelo RoBERTa...")

    # Usamos un modelo preentrenado de RoBERTa para análisis de sentimientos (ejemplo clásico)
    nombre_modelo = "cardiffnlp/twitter-roberta-base-sentiment-latest"

    # Cargamos el pipeline de clasificación de textos de Hugging Face
    clasificador = pipeline("sentiment-analysis", model=nombre_modelo, tokenizer=nombre_modelo)

    # Entrada de texto interactiva para probar el modelo
    texto_usuario = input("Escribe un texto para analizar con RoBERTa: ").strip()

    print(f"\nAnalizando texto con RoBERTa...\n")

    # Ejecución del modelo
    resultado = clasificador(texto_usuario)

    print("--- Resultado del Análisis ---")
    print(f"Etiqueta: {resultado[0]['label']}")
    print(f"Confianza: {resultado[0]['score']:.4f}")

if __name__ == "__main__":
    ejecutar_roberta_local()