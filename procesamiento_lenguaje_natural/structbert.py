from datasets import Dataset
from transformers import AutoTokenizer, AutoModelForSequenceClassification, Trainer, TrainingArguments, DataCollatorWithPadding
import numpy as np
import evaluate

def main():
    print("1. Creando un dataset local de prueba en memoria...")
    raw_data = {
        "text": [
            "The movie was an absolute masterpiece with incredible acting.",
            "Terrible plot, boring characters, and a complete waste of time.",
            "I loved the cinematography and the soundtrack was breathtaking.",
            "Predictable and dull, I fell asleep halfway through.",
            "An emotional roller coaster that keeps you hooked till the end.",
            "Worst film of the year, nothing made sense."
        ],
        "label": [1, 0, 1, 0, 1, 0]
    }

    dataset = Dataset.from_dict(raw_data)
    dataset = dataset.train_test_split(test_size=0.33, seed=42)

    print("2. Cargando el Tokenizer y el modelo StructBERT...")
    model_checkpoint = "bayartsogt/structbert-large"

    tokenizer = AutoTokenizer.from_pretrained(model_checkpoint)

    model = AutoModelForSequenceClassification.from_pretrained(
        model_checkpoint,
        num_labels=2
    )

    print("3. Tokenizando los datos...")
    def preprocess_function(examples):
        return tokenizer(examples["text"], truncation=True, max_length=128)

    encoded_datasets = dataset.map(preprocess_function, batched=True)

    print("4. Configurando los argumentos de entrenamiento...")
    training_args = TrainingArguments(
        output_dir="./results_structbert",
        eval_strategy="epoch",
        save_strategy="epoch",
        learning_rate=2e-5,
        per_device_train_batch_size=2,
        per_device_eval_batch_size=2,
        num_train_epochs=2,
        weight_decay=0.01,
        load_best_model_at_end=True,
        logging_steps=1
    )

    metric = evaluate.load("accuracy")

    def compute_metrics(eval_pred):
        logits, labels = eval_pred
        predictions = np.argmax(logits, axis=-1)
        return metric.compute(predictions=predictions, references=labels)

    # Data collator para solucionar el problema de longitud variable en los batches
    data_collator = DataCollatorWithPadding(tokenizer=tokenizer)

    print("5. Inicializando el Trainer...")
    trainer = Trainer(
        model=model,
        args=training_args,
        train_dataset=encoded_datasets["train"],
        eval_dataset=encoded_datasets["test"],
        data_collator=data_collator,
        compute_metrics=compute_metrics,
    )

    print("6. Iniciando el entrenamiento (Fine-Tuning)...")
    trainer.train()

    print("7. Evaluando el modelo final...")
    eval_results = trainer.evaluate()
    print(f"Resultados de evaluación: {eval_results}")

if __name__ == "__main__":
    main()