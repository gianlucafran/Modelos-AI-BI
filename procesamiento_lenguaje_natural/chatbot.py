from datasets import Dataset
from transformers import (
    AutoTokenizer,
    AutoModelForSequenceClassification,
    Trainer,
    TrainingArguments,
    DataCollatorWithPadding,
    pipeline
)
import numpy as np
import evaluate

def main():
    print("=== PASO 1: Creando el dataset local de entrenamiento ===")
    raw_data = {
        "text": [
            "The movie was an absolute masterpiece with incredible acting.",
            "Terrible plot, boring characters, and a complete waste of time.",
            "I loved the cinematography and the soundtrack was breathtaking.",
            "Predictable and dull, I fell asleep halfway through.",
            "An emotional roller coaster that keeps you hooked till the end.",
            "Worst film of the year, nothing made sense."
        ],
        "label": [1, 0, 1, 0, 1, 0] # 1: Positivo, 0: Negativo
    }

    dataset = Dataset.from_dict(raw_data)
    dataset = dataset.train_test_split(test_size=0.33, seed=42)

    print("\n=== PASO 2: Cargando Tokenizer y modelo StructBERT ===")
    model_checkpoint = "bayartsogt/structbert-large"
    tokenizer = AutoTokenizer.from_pretrained(model_checkpoint)

    model = AutoModelForSequenceClassification.from_pretrained(
        model_checkpoint,
        num_labels=2
    )

    print("\n=== PASO 3: Tokenizando los datos ===")
    def preprocess_function(examples):
        return tokenizer(examples["text"], truncation=True, max_length=128)

    encoded_datasets = dataset.map(preprocess_function, batched=True)

    print("\n=== PASO 4: Configurando argumentos de entrenamiento ===")
    training_args = TrainingArguments(
        output_dir="./results_structbert",
        eval_strategy="epoch",
        save_strategy="epoch",
        learning_rate=2e-5,
        per_device_train_batch_size=2,
        per_device_eval_batch_size=2,
        num_train_epochs=2,
        weight_decay=0.01,
        load_best_model_at_end=True,
        logging_steps=1,
        report_to="none" # Evita logs innecesarios
    )

    metric = evaluate.load("accuracy")

    def compute_metrics(eval_pred):
        logits, labels = eval_pred
        predictions = np.argmax(logits, axis=-1)
        return metric.compute(predictions=predictions, references=labels)

    data_collator = DataCollatorWithPadding(tokenizer=tokenizer)

    print("\n=== PASO 5: Inicializando el Trainer ===")
    trainer = Trainer(
        model=model,
        args=training_args,
        train_dataset=encoded_datasets["train"],
        eval_dataset=encoded_datasets["test"],
        data_collator=data_collator,
        compute_metrics=compute_metrics,
    )

    print("\n=== PASO 6: Iniciando Fine-Tuning ===")
    trainer.train()

    print("\n=== PASO 7: Evaluando el modelo final ===")
    eval_results = trainer.evaluate()
    print(f"Resultados de evaluación: {eval_results}")

    # Guardamos el modelo entrenado localmente para que el chatbot lo use
    model_path = "./structbert_finetuned"
    trainer.save_model(model_path)
    tokenizer.save_pretrained(model_path)
    print(f"\n¡Modelo guardado exitosamente en '{model_path}'!")

    print("\n" + "="*50)
    print("🤖 INICIANDO CHATBOT CON EL MODELO ENTRENADO")
    print("="*50)
    print("Escribe una frase para analizar su sentimiento (o escribe 'salir' para terminar).\n")

    # Creamos el pipeline usando nuestro modelo recién entrenado
    chatbot_pipeline = pipeline("text-classification", model=model_path, tokenizer=model_path)

    while True:
        user_input = input("Tú: ")

        if user_input.lower() in ["salir", "exit", "quit"]:
            print("Chatbot: ¡Hasta luego!")
            break

        if not user_input.strip():
            continue

        result = chatbot_pipeline(user_input)[0]
        label_id = result['label'] # Ejemplo: "LABEL_1" o "LABEL_0"
        score = result['score'] * 100

        # Mapeamos la etiqueta numérica a texto legible
        sentiment = "Positivo 😊" if "1" in label_id else "Negativo ❌"

        print(f"Bot (StructBERT): Sentimiento detectado -> {sentiment} (Confianza: {score:.2f}%)\n")

if __name__ == "__main__":
    main()