# 2. Tokenizar todo el conjunto (lo que hablamos antes)
from transformers import BertTokenizer
tokenizer = BertTokenizer.from_pretrained('bert-base-uncased')

def tokenize_batch(batch):
    return tokenizer(batch["text"], truncation=True, padding="max_length", max_length=128)

# Esto aplicará la tokenización a todo tu dataset de forma eficiente
tokenized_data = dataset.map(tokenize_batch, batched=True)

import torch
from transformers import BertModel

# Cargamos el modelo BERT pre-entrenado
model = BertModel.from_pretrained('bert-base-uncased')

# Asegúrate de que tus datos sean tensores de PyTorch
input_ids = torch.tensor(tokenized_data['input_ids'])

# Pasamos los datos por el modelo
with torch.no_grad():
    outputs = model(input_ids)

# El resultado 'last_hidden_state' contiene los vectores (embeddings)
embeddings = outputs.last_hidden_state
print(embeddings.shape) # [batch_size, sequence_length, hidden_size]